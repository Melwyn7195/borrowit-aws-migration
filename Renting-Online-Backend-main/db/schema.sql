-- ---------------------------------------------------------------------------
-- get_product_avg_rating
-- ---------------------------------------------------------------------------
--
-- Required. models/Product.js and models/Order.js call this in nearly every
-- SELECT, so product listing, product detail, search and the whole order API
-- fail without it. Returns 0 rather than NULL for an unreviewed product,
-- because searchProducts compares the result with >= in a HAVING clause.

CREATE OR REPLACE FUNCTION get_product_avg_rating(p_product_id integer)
RETURNS numeric
LANGUAGE sql
STABLE
AS $$
  SELECT COALESCE(ROUND(AVG(satisfaction_score)::numeric, 2), 0)
  FROM "Review"
  WHERE product_id = p_product_id;
$$;

