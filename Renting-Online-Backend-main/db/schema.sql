-- Keeps updated_at honest. Several models set it explicitly and several do not
-- (Product.updateProduct, for one), which is why this is a trigger rather than
-- a column default.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

