CREATE TABLE IF NOT EXISTS "User" (
  user_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username           text        NOT NULL UNIQUE,
  email              text        NOT NULL UNIQUE,
  password           text        NOT NULL,
  full_name          text,
  phone              text,
  avatar_url         text,
  address            text,
  role               text        NOT NULL DEFAULT 'customer',
  status             text        NOT NULL DEFAULT 'pending',
  rating             numeric(3,2),
  total_orders       integer     NOT NULL DEFAULT 0,
  email_verified     boolean     NOT NULL DEFAULT false,
  verification_token text,
  token_expires      timestamptz,
  reset_token        text,
  reset_expires      timestamptz,
  last_login_at      timestamptz,
  created_at         timestamptz NOT NULL DEFAULT NOW(),
  updated_at         timestamptz NOT NULL DEFAULT NOW()
);

-- role   IN ('customer', 'seller', 'admin')
-- status IN ('active', 'suspended', 'pending')
--
-- These were CHECK constraints originally - db/drop_all_constraints.sql drops
-- "User_role_check" and "User_status_check" by name. They are deliberately not
-- recreated here, because that script exists precisely because the app outgrew
-- them. Documented as comments so the intent survives.

CREATE INDEX IF NOT EXISTS user_role_idx   ON "User" (role);
CREATE INDEX IF NOT EXISTS user_status_idx ON "User" (status);

